"""World seaports for the port lookup: name, country, UN/LOCODE and the words that name the port in a news report.

Built for Border Watch from public knowledge of the ports and their UN/LOCODE codes (UNECE). Caribbean first.
A port is only matched by words that clearly mean the port ("port of Kingston", "Kingston Wharves"), not by the
city name alone, unless the place is essentially only a port (Algeciras, Felixstowe, Tema).
"""

def _p(name, country, code, *aliases, bare=False):
    city = name.split(" (")[0].split(" / ")[0]
    words = [f"port of {city}", f"{city} port", f"{city} harbour", f"{city} harbor", f"{city} seaport",
             f"puerto de {city}", f"port de {city}", f"porto de {city}"] + list(aliases)
    if bare:
        words.append(city)
    return {"name": name, "country": country, "code": code, "words": list(dict.fromkeys(words))}


